from app.db.models import PostChunk
from ollama import AsyncClient
import json
import re

client = AsyncClient()
MODEL_NAME = "qwen3:4b-instruct-2507-q4_K_M"

def evaluate_with_llm_judge(query: str, combined_rows: list[tuple[PostChunk, float]]):
    """
    Uses an LLM to evaluate the quality of a RAG-generated answer.

    Args:
    query (str): The user's original query.
    combined_rows(list): Including the list of tuples of PostChunk and similarity.
    """

    prompt = """
    You are an impartial judge evaluating the quality of an answer generated by a Retrieval-Augmented Generation (RAG) system.

    Your task is to evaluate the generated answer based on two criteria:
    1. **Factuality**: Is the generated answer factually grounded in the provided context? A faithful answer only uses information present in the 
    context and does not contradict it.
    2. **Answer Relevance**: Is the generated answer relevant and helpful for the given query?

    You must provide a score from 1 to 5 for each criterion (1=Poor, 5=Excellent) and a brief explanation for your scores.

     **Query:**
    {query}
    **Retrieved Context:**
    {context}
    **Generated Answer:**
    {generated_answer}

    Please provide your evaluation *only* in a valid JSON format with the 
    following keys: "factuality_score", "factuality_reasoning", 
    "relevance_score", "relevance_reasoning". Your response MUST be a single 
    JSON object and nothing else.
    """

    try:
        response = client.chat(
            model=MODEL_NAME,
            messages=[
                {
                    "role": "system",
                    "content": "You are an expert evaluator of AI-generated text that responses only in valid JSON"
                },
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            options={
                "tempature": 0,
                "seed": 42,
                "num_ctx": 4096
            }
        )
        response_text = response.message.content

        # Check whether the res in JSON format? Necessecery?
        json_match = re.search(r'\{.*\}', response_text, re.DOTALL)

        if json_match:
            json_str = json_match.group(0)
            evaluation = json.loads(json_str)
            return evaluation
        else:
            print("Error: Could not find a valid JSON object in the model's response.")
            print(f"Full response: {response_text}")
            return None
        
    except Exception as e:
        print(f"An error occured during API call or JSON parsing: {e}")
        return None
    